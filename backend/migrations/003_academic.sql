REVOKE ALL ON students, homework_assignments, homework_checks FROM PUBLIC;
DO $$ DECLARE api_role TEXT;
BEGIN
    FOREACH api_role IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = api_role) THEN
            EXECUTE format('REVOKE ALL ON students, homework_assignments, homework_checks FROM %I', api_role);
        END IF;
    END LOOP;
END $$;
